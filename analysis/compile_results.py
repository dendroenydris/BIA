"""Collect the evaluator agreement and Qwen3-VL label-imbalance results quoted in the paper into results/results_tables.md.

Reads the outputs of qwen3vl_human_agreement.py, clip_human_agreement.py (b32, l14ens) and label_imbalance.py.
Numbers are rounded here only (four decimals for estimates, three for kappa and p-values).

usage: python analysis/compile_results.py
"""
import csv
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from paths import RESULTS as A  # noqa: E402

OUT = A / 'results_tables.md'
AXES = [('gender', 'Gender'), ('skin_tone', 'Skin tone'), ('ethnicity', 'Ethnicity'), ('culture', 'Geo-culture'), ('age', 'Age')]
LABELS = {'skin_tone': ['light', 'medium', 'dark'],
          'ethnicity': ['white', 'black', 'east_asian', 'south_southeast_asian', 'middle_eastern', 'latino'],
          'gender': ['woman', 'man'], 'age': ['child', 'teenager', 'young_adult', 'middle_aged', 'older_adult'],
          'culture': ['western_european', 'south_asian', 'east_asian', 'middle_eastern', 'african', 'latin_american']}
ARM = {'baseline': 'B', 'bias_aware': 'M', 'llm_assisted': 'L', 'C': 'C', 'I': 'I'}


def rd(path):
    return list(csv.DictReader(open(path, newline='')))


def f(x, d=4):
    return '' if x in ('', None) else f'{float(x):.{d}f}'


def p(x):
    v = float(x)
    return '<0.001' if v < 0.001 else f'{v:.3f}'


def validation():
    v = {r['field']: r for r in rd(A / 'agreement/qwen3vl_vs_raters/agreement.csv')}
    live = {r['field']: r for r in rd(A / 'agreement/qwen3vl_vs_raters_first_parser/agreement.csv')}
    out = ['## Evaluator agreement with the human raters (60 archive images)', '',
           '| Attribute | CLIP B/32 (A; B) | CLIP L/14 ens. (A; B) | Qwen3-VL (A; B) | Qwen3-VL mean | Qwen3-VL mean, first parser (58 images) | Rater A vs B | Reference bound |',
           '|---|---|---|---|---|---|---|---|']
    clip = {}
    for name, d in (('b32', 'agreement/clip_b32_vs_raters'), ('l14', 'agreement/clip_l14_vs_raters')):
        for r in rd(A / d / 'agreement.csv'):
            if r['scope'] == 'all_60':
                clip[(name, r['axis'], r['rater'])] = r
    m = {'gender_presentation': 'Gender Bias', 'skin_tone': 'Skin Tone Bias', 'ethnic_appearance': 'Ethnic Representation Bias',
         'cultural_scene': 'Geo-Cultural Bias', 'age_appearance': None}
    for fld, ax in m.items():
        def ck(n, r):
            x = clip.get((n, ax, r))
            return f"{float(x['kappa']):.3f} (n={x['n_comparable']})" if x and x.get('kappa') else 'n/a'
        q = v[fld]
        out.append(f"| {fld} | {ck('b32', 'A')}; {ck('b32', 'B')} | {ck('l14', 'A')}; {ck('l14', 'B')} | "
                   f"{f(q['kappa_A'], 3)} {q['ci_A']}; {f(q.get('kappa_B'), 3) or 'n/a'} {q.get('ci_B', '')} | {f(q['evaluator_human_kappa'], 3)} | "
                   f"{f(live[fld]['evaluator_human_kappa'], 3)} | {f(q['human_human_kappa'], 3) or 'n/a'} | {q['reference_bound']} |")
    return out


def design(run, title):
    cmp_ = rd(A / f'qwen3vl/{run}/comparisons.csv')
    desc = rd(A / f'qwen3vl/{run}/condition_descriptives.csv')
    cells = rd(A / f'qwen3vl/{run}/cells.csv')
    out = [f'## {title}', '', '| Attribute | Condition | Prompts | Mean label MAD | Non-substantive share | Pooled label shares |', '|---|---|---|---|---|---|']
    for ax, axn in AXES:
        for d in [r for r in desc if r['axis'] == ax]:
            rs = [c for c in cells if c['axis'] == ax and c['arm'] == d['arm']]
            sub = sum(int(c['substantive']) for c in rs)
            shares = ', '.join(f"{l} {sum(int(c[f'n_{l}'] or 0) for c in rs) / sub:.3f}" for l in LABELS[ax]) if sub else ''
            out.append(f"| {axn} | {ARM[d['arm']]} | {d['prompts_with_substantive']}/{d['prompts']} | {f(d['mean_label_mad'])} | "
                       f"{f(d['mean_non_substantive_share'], 3)} | {shares} |")
    out += ['', '| Attribute | Comparison | n | Mean Δ | 95% CI | SD Δ | dz | p (sign-flip) | p (Holm) | MDE |', '|---|---|---|---|---|---|---|---|---|---|']
    for ax, axn in AXES:
        for r in [r for r in cmp_ if r['axis'] == ax]:
            a, _, b = r['contrast'].split(' ')
            if 'mean_difference' not in r or r['mean_difference'] == '':
                continue
            out.append(f"| {axn} | {ARM[a]}−{ARM[b]} | {r['prompts_used']} | {f(r['mean_difference'])} | "
                       f"[{f(r['ci95_low'])}, {f(r['ci95_high'])}] | {f(r['sd_difference'])} | {f(r['cohen_dz'], 2)} | "
                       f"{p(r['p_sign_flip'])} | {p(r['p_holm'])} | {f(r['mde_label_mad'])} |")
    return out


lines = ['# Results tables (generated by compile_results.py; do not edit by hand)', ''] + validation() + ['']
for run, title in (('main_sd21', 'Main experiment, SD 2.1, Qwen3-VL (50 images per prompt and condition)'),
                   ('main_flux', 'Main experiment, FLUX.1-schnell, Qwen3-VL (50 images per prompt and condition)'),
                   ('matched_sd21', 'Matched-clause experiment, SD 2.1, Qwen3-VL (50 images per prompt and version)'),
                   ('original_archive', 'Original archive of 600 SD 2.1 images, Qwen3-VL (5 images per prompt and condition)')):
    lines += design(run, title) + ['']
OUT.write_text('\n'.join(lines) + '\n')
print(OUT.relative_to(A.parent), len(lines), 'lines')
